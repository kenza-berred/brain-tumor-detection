"""Write the numbers of the latest run as LaTeX macros for the technical report.

Run with:  python -m src.utils.report_numbers   (after `dvc repro` and compare_runs)
Writes:    report/numbers.tex     \\newcommand{\\fpThirtyTwoMapFifty}{0.871} ...
           report/comparison.tex  \\comparisonRows, the rows of the baseline-vs-advanced table

A value that does not exist yet is written as "--" so the report always compiles.
"""

from __future__ import annotations

import csv
import json

from src.utils.common import ROOT

WORDS = {"fp32": "FpThirtyTwo", "fp16": "FpSixteen", "int8": "IntEight", "pytorch": "Pytorch"}
METRICS = {
    "precision": "Precision",
    "recall": "Recall",
    "mAP50": "MapFifty",
    "mAP50_95": "Map",
    "cpu_ms": "Ms",
    "size_mb": "Mb",
}


def read(name: str) -> dict:
    path = ROOT / "reports" / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def fmt(value, digits: int = 3) -> str:
    return "--" if value is None else f"{value:.{digits}f}"


def main() -> None:
    out = ROOT / "report"
    out.mkdir(exist_ok=True)
    export, train = read("export.json"), read("metrics.json")
    meta_path = ROOT / "models" / "metadata.json"
    meta = json.loads(meta_path.read_text(encoding="utf-8")) if meta_path.exists() else {}

    lines = ["% generated by src/utils/report_numbers.py -- do not edit"]
    for variant, vword in WORDS.items():
        for metric, mword in METRICS.items():
            value = export.get(f"{variant}_{metric}")
            if value is None and variant == "fp32":  # export.json written by the first export script
                value = export.get(f"onnx_{metric}")
            digits = 1 if metric in ("cpu_ms", "size_mb") else 3
            lines.append(f"\\newcommand{{\\{vword.lower()}{mword}}}{{{fmt(value, digits)}}}")
    for metric, mword in METRICS.items():
        lines.append(f"\\newcommand{{\\train{mword}}}{{{fmt(train.get(metric))}}}")
    lines.append(f"\\newcommand{{\\modelVersion}}{{{meta.get('version') or '--'}}}")
    lines.append(f"\\newcommand{{\\datasetName}}{{{meta.get('dataset') or 'Ultralytics Brain Tumor'}}}")
    (out / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")

    rows = []
    comparison = ROOT / "reports" / "comparison.csv"
    if comparison.exists():
        with open(comparison, encoding="utf-8") as f:
            for r in csv.DictReader(f):
                aug = "oui" if r["augment"].lower() == "true" else "non"
                cells = [
                    r["run"],
                    r["model"],
                    r["epochs"],
                    aug,
                    r["precision"],
                    r["recall"],
                    r["mAP50"],
                    r["mAP50_95"],
                    r["minutes"],
                ]
                rows.append(" & ".join(c.replace("_", "\\_") for c in cells) + " \\\\")
    body = "\n".join(rows or ["\\multicolumn{9}{c}{--} \\\\"])
    # A macro rather than raw rows: \input inside a tabular breaks \bottomrule.
    (out / "comparison.tex").write_text(
        f"\\newcommand{{\\comparisonRows}}{{%\n{body}\n}}\n", encoding="utf-8"
    )
    print(f"Wrote {out / 'numbers.tex'} and {out / 'comparison.tex'}")


if __name__ == "__main__":
    main()
